#pragma once

#include "Data.h"
#include <string>
#include <vector>

/**
 * @brief Форматирует данные рейтинга и хранит состояние прокрутки экрана рейтинга.
 */
class RankingView
{
  public:
    /**
     * @brief Заменяет отображаемые данные рейтинга и сбрасывает смещение прокрутки.
     * @param results Результаты рейтинга для отображения.
     */
    void setRanking(const std::vector<PlayerResult>& results);

    /**
     * @brief Перемещает видимую страницу вверх на одну страницу, если это возможно.
     */
    void scrollUp();

    /**
     * @brief Перемещает видимую страницу вниз на одну страницу, если это возможно.
     */
    void scrollDown();

    /**
     * @brief Возвращает видимую страницу к началу рейтинга.
     */
    void resetScroll();

    /**
     * @brief Создает форматированный текст для разделов одиночной игры и дуэли.
     * @return Многострочный текст с текущей страницей рейтинга.
     */
    std::string buildText() const;

  private:
    /** @brief Все результаты, доступные представлению в текущий момент. */
    std::vector<PlayerResult> allResults;

    /** @brief Индексное смещение первой видимой страницы результатов. */
    int offset{0};

    /** @brief Максимальное количество записей, отображаемых на странице каждого раздела. */
    int pageSize{10};
};
